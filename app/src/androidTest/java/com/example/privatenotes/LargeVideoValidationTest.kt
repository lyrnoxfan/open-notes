package com.example.privatenotes

import androidx.compose.ui.semantics.SemanticsProperties
import androidx.compose.ui.test.*
import androidx.compose.ui.test.junit4.createAndroidComposeRule
import androidx.test.core.app.ApplicationProvider
import com.example.privatenotes.data.backup.StreamingMediaArchive
import com.example.privatenotes.feature.notes.InlineMediaSyntax
import com.example.privatenotes.feature.notes.RichMediaEditText
import kotlinx.coroutines.runBlocking
import org.junit.Assert.*
import org.junit.Rule
import org.junit.Test
import java.io.File
import java.security.MessageDigest

/** Isolated test install, with a real playable H.264 file generated by ffmpeg on the runner. */
@ScriptDriven
class LargeVideoValidationTest {
    @get:Rule val compose = createAndroidComposeRule<MainActivity>()
    private val app get() = ApplicationProvider.getApplicationContext<PrivateNotesApp>()
    private val container get() = app.container
    private fun hex(d: ByteArray) = d.joinToString("") { "%02x".format(it) }
    private fun log(stage: String) {
        val info = android.os.Debug.MemoryInfo(); android.os.Debug.getMemoryInfo(info)
        android.util.Log.i("LargeMediaValidation", "$stage pssKiB=${info.totalPss} heapUsed=${Runtime.getRuntime().totalMemory()-Runtime.getRuntime().freeMemory()} freeBytes=${app.filesDir.usableSpace}")
    }
    private fun editor(): RichMediaEditText {
        fun find(v: android.view.View): RichMediaEditText? = if (v is RichMediaEditText) v else
            (v as? android.view.ViewGroup)?.let { g -> (0 until g.childCount).firstNotNullOfOrNull { find(g.getChildAt(it)) } }
        return checkNotNull(find(compose.activity.window.decorView))
    }
    @Test fun largePlayableVideoBackupRestoreAndPlayback() {
        val file = File(app.filesDir, "large-video.mp4")
        assertTrue("fixture missing or below 40 MiB: ${file.length()}", file.length() > 40L * 1024 * 1024)
        val hash = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input -> val buf = ByteArray(65536); while (true) { val n = input.read(buf); if (n < 0) break; hash.update(buf,0,n) } }
        val expected = hex(hash.digest())
        android.util.Log.i("LargeMediaValidation", "fixtureBytes=${file.length()} sha256=$expected")
        log("before-import")
        val id = runBlocking {
            val id = container.noteRepository.createNote("large video validation", "before")
            val mediaId = file.inputStream().use { container.mediaRepository.importStream(id, "large-video.mp4", "video/mp4", it, bodyForId = { mediaId -> "before ${InlineMediaSyntax.reference(mediaId)} after" }) }
            val item = container.mediaRepository.list(id).single()
            assertEquals(mediaId, item.id); assertEquals(file.length(), item.size); assertEquals(expected, item.sha256)
            id
        }
        log("after-import")
        val archive = File(app.cacheDir, "large-video-validation.pnm")
        val body = runBlocking { container.noteRepository.findById(id)!!.content }
        runBlocking { archive.outputStream().use { StreamingMediaArchive(container.database).write(it, "test-password".toCharArray(), "test", 1000) } }
        android.util.Log.i("LargeMediaValidation", "archiveBytes=${archive.length()}")
        log("after-backup")
        runBlocking {
            container.database.clearAllTables()
            archive.inputStream().use { StreamingMediaArchive(container.database).restore(it, "test-password".toCharArray()) }
            assertEquals(body, container.noteRepository.findById(id)!!.content)
            val item = container.mediaRepository.list(id).single()
            assertEquals(file.length(), item.size); assertEquals(expected, item.sha256)
            val digest = MessageDigest.getInstance("SHA-256")
            container.mediaRepository.videoSource(item).use { source ->
                val buf = ByteArray(65536); var offset = 0L
                while (offset < source.size) { val n = source.readAt(offset, buf, 0, buf.size); assertTrue(n > 0); digest.update(buf, 0, n); offset += n }
                assertEquals(file.length(), offset)
            }
            assertEquals(expected, hex(digest.digest()))
        }
        log("after-restore-and-hash")
        compose.waitUntil(30000) { compose.onAllNodesWithTag("note_row_$id").fetchSemanticsNodes().isNotEmpty() }
        compose.onNodeWithTag("note_row_$id").performClick()
        compose.waitUntil(30000) { compose.onAllNodesWithTag("inline_media_editor").fetchSemanticsNodes().isNotEmpty() }
        compose.waitUntil(10000) { compose.activity.window.decorView.hasWindowFocus() }
        val native = androidx.test.espresso.Espresso.onView(androidx.test.espresso.matcher.ViewMatchers.withTagValue(org.hamcrest.Matchers.`is`("rich_media_native_editor")))
        compose.runOnUiThread {
            val e = editor(); val canonical = RichMediaEditText.canonical(e.text)
            val media = InlineMediaSyntax.ids(canonical).single()
            val offset = RichMediaEditText.displayOffset(canonical, canonical.indexOf(InlineMediaSyntax.reference(media)))
            e.bringPointIntoView(offset)
        }
        native.perform(androidx.test.espresso.action.GeneralClickAction(androidx.test.espresso.action.Tap.SINGLE,
            androidx.test.espresso.action.CoordinatesProvider { view ->
                val e = view as RichMediaEditText; val canonical = RichMediaEditText.canonical(e.text)
                val media = InlineMediaSyntax.ids(canonical).single()
                val offset = RichMediaEditText.displayOffset(canonical, canonical.indexOf(InlineMediaSyntax.reference(media)))
                val line = e.layout.getLineForOffset(offset); val xy = IntArray(2); e.getLocationOnScreen(xy)
                floatArrayOf(xy[0] + e.width / 2f, xy[1] + e.totalPaddingTop + (e.layout.getLineTop(line) + e.layout.getLineBottom(line)) / 2f - e.scrollY)
            }, androidx.test.espresso.action.Press.FINGER))
        compose.waitUntil(60000) { compose.onAllNodesWithTag("media_play_pause").fetchSemanticsNodes().isNotEmpty() }
        compose.onNodeWithTag("media_play_pause").performClick()
        compose.waitUntil(60000) {
            compose.onAllNodesWithTag("media_position").fetchSemanticsNodes().firstOrNull()
                ?.config?.get(SemanticsProperties.Text)?.joinToString { it.text }?.substringBefore(" /")?.toIntOrNull()?.let { it >= 2 } == true
        }
        log("playback-progressed-to-two-seconds")
        archive.delete(); file.delete()
    }
}
